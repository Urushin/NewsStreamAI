let currentLanguage = "fr";

export function setLanguage(lang) {
  currentLanguage = (lang || "fr").toLowerCase().slice(0, 2);
  if (!I18N[currentLanguage]) currentLanguage = "fr";
  try {
    localStorage.setItem("mizan.lang", currentLanguage);
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = currentLanguage === "ar" ? "rtl" : "ltr";
  } catch (e) {}
  return currentLanguage;
}

export function getLanguage() {
  if (!currentLanguage) {
    try {
      currentLanguage = localStorage.getItem("mizan.lang") || "fr";
    } catch (e) {
      currentLanguage = "fr";
    }
  }
  return currentLanguage;
}

export function t(key, vars = {}) {
  const lang = getLanguage();
  let str = I18N[lang]?.[key] || I18N["en"]?.[key] || I18N["fr"]?.[key] || key;
  if (vars && typeof vars === "object") {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}
